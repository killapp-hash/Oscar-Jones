export type StoryMode = 'original' | 'edited';

export function getChapterParagraphs(chapter: Chapter, mode: StoryMode): string[] {
  if (mode === 'original' && chapter.originalParagraphs) {
    return chapter.originalParagraphs;
  }
  return chapter.paragraphs;
}

